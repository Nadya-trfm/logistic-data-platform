insert into core.fact_price (
    price_id,
    created_at,
    loading_date,
    end_loading_date,
    loading_city_gcid,
    unloading_city_gcid,
    distance,
    total_weight,
    total_volume,
    subscriber_id,
    organization_id,
    price_type,
    is_fact,
    complex,
    currency_code,
    price_orig,
    fx_rate,
    price_rub,
    nearest_rate_date,
    outlier_mark,
    weight_category,
    volume_category,
    body_group_primary,
    etl_run_id
)
select
    s.price_id,
    s.created_at,
    s.loading_date,
    s.end_loading_date,
    s.loading_city_gcid,
    s.unloading_city_gcid,
    s.distance,
    s.total_weight,
    s.total_volume,
    s.subscriber_id,
    s.organization_id,
    s.price_type,
    s.is_fact,
    s.complex,
    s.currency_code,
    s.price_orig,
    s.fx_rate,
    s.price_orig * s.fx_rate,
    s.nearest_rate_date,
    s.outlier_mark,
    coalesce(s.weight_category_src, s.weight_category_calc),
    coalesce(s.volume_category_src, s.volume_category_calc),
    s.body_group_primary,
    %(run_id)s
from stg_prices s
where
    s.reason is null;
    